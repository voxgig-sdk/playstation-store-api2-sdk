import {
  Content,
  File,
  cmp,
  entitySpecMap,
  optionSpec,
} from '@voxgig/sdkgen'


import {
  Model,
} from '@voxgig/apidef'


import {
  formatGoString,
} from './utility_go'


const Schema = cmp(async function Schema(props: any) {
  const ctx$ = props.ctx$
  const target = props.target

  const model: Model = ctx$.model

  const optspec = optionSpec(model, target.name)
  const entityspec = entitySpecMap(model, target.name) || {}

  File({ name: 'schema.' + target.ext }, () => {
    Content(`package core

import (
	"encoding/json"
)

// ${model.const.Name} ${target.Name} SDK: generated schemas. Do not edit.
//
// Generated from the model: \`main.kit.optspec\` and each feature's
// \`config.options\` for OPTSPEC; entity \`fields{}.type\` for ENTITYSPEC.

const optspecJSON = ${formatGoString(JSON.stringify(optspec))}

const entityspecJSON = ${formatGoString(JSON.stringify(entityspec))}

// Parsed ONCE, at package init. The spec is read on every client
// construction and never mutated, so a per-call parse would be pure waste —
// and a shared map is safe here for the same reason the spec is a constant:
// MakeOptions validates AGAINST it and writes into the options, never into
// the spec.
var (
	OPTSPEC    = mustSpec(optspecJSON)
	ENTITYSPEC = mustSpec(entityspecJSON)
)

func mustSpec(src string) map[string]any {
	var out map[string]any
	if err := json.Unmarshal([]byte(src), &out); err != nil {
		// Unreachable: generated by json.Marshal's counterpart and never
		// edited by hand. Panic rather than hand back an empty spec, which
		// would validate everything and fail far from the cause.
		panic("${model.const.Name}: embedded schema is not valid JSON: " + err.Error())
	}
	return out
}
`)
  })
})


export {
  Schema
}
